#!/usr/bin/env kotlinr

/**
 * Supply the Native test link friend paths missing in Kotlin Toolchain 0.13.
 * Native compilation runs from the compiler distribution, so relative paths
 * cannot identify the already-loaded main KLIB. No machine path is tracked.
 */
import java.io.File

require(args.size <= 1) { "Usage: kotlinr tools/configure-native-tests.main.kts [build-directory]" }
val root = File(".").canonicalFile
check(File(root, "module.yaml").isFile) { "Run from the repository root" }
val build = (args.singleOrNull()?.let(::File) ?: File(root, "build")).canonicalFile
fun yamlString(value: String): String = "\"" + value
    .replace("\\", "\\\\").replace("\"", "\\\"")
    .replace("\r", "\\r").replace("\n", "\\n").replace("\t", "\\t") + "\""
val targets = listOf("MacosArm64", "MacosX64", "LinuxX64", "LinuxArm64",
    "MingwX64", "IosArm64", "IosSimulatorArm64", "IosX64")
val output = File(root, ".native-test-friends.module-template.yaml")
output.writeText(buildString {
    append("# Generated by tools/configure-native-tests.main.kts; do not commit.\n")
    for (target in targets) {
        val friends = listOf("Debug", "Release").joinToString(File.pathSeparator) { variant ->
            File(build, "tasks/_krogu-math_compile$target$variant/krogu-math.klib").path
        }
        append("test-settings@").append(target.replaceFirstChar(Char::lowercaseChar)).append(":\n")
        append("  kotlin:\n    freeCompilerArgs:\n      - ")
            .append(yamlString("-friend-modules=$friends")).append('\n')
    }
})
println("Native test friend paths configured for ${targets.size} targets; build directory: $build")
