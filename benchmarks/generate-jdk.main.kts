#!/usr/bin/env kotlinr
import java.io.File
val root = File("benchmarks")
val text = "// Generated by benchmarks/generate-jdk.main.kts from our workload expressions.\n" +
    File(root, "standard/src/Workloads.kt").readText()
        .replace("io.heapy.krogu.math", "java.math")
        .replace("fun kroguWorkloads", "fun jdkWorkloads")
        .replace("data class Workload(val name: String, val run: (Int) -> Any)\n", "")
val target = File(root, "standard/src@jvm/JdkWorkloads.kt")
if ("--check" in args) check(target.readText() == text) { "Run benchmarks/generate-jdk.main.kts" }
else target.writeText(text)
