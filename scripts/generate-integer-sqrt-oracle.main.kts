/** Integer square-root values, identities and callback traces from public JDK APIs. Usage: [--check]. */
import java.io.File
import java.math.BigInteger

check(Runtime.version().toString() in listOf("25.0.4+9", "25.0.4+9-LTS")) { "Requires JDK 25.0.4+9" }
check(args.all { it == "--check" })
class Probe(text: String, val trace: StringBuilder, val mode: String) : BigInteger(text) {
    private val replacement = BigInteger("7")
    private fun call(name: String) { trace.append("$name;"); if (mode == "throw") throw IllegalStateException("$name callback") }
    override fun toByte(): Byte = super.toInt().toByte()
    override fun toShort(): Short = super.toInt().toShort()
    override fun sqrt(): BigInteger { call("sqrt"); return if (mode == "replace") replacement else super.sqrt() }
    override fun sqrtAndRemainder(): Array<BigInteger> { call("pair"); return when (mode) {
        "replace" -> arrayOf(replacement, replacement); "empty-pair" -> emptyArray(); else -> super.sqrtAndRemainder()
    } }
    override fun compareTo(other: BigInteger): Int { call("compare"); return if (mode == "replace") -1 else super.compareTo(other) }
    override fun bitLength(): Int { call("bits"); return if (mode == "replace") 1 else super.bitLength() }
    override fun signum(): Int { call("signum"); return if (mode == "replace") -1 else super.signum() }
    override fun divide(other: BigInteger): BigInteger { call("divide"); return if (mode == "replace") replacement else super.divide(other) }
    override fun subtract(other: BigInteger): BigInteger { call("subtract"); return if (mode == "replace") replacement else super.subtract(other) }
    override fun multiply(other: BigInteger): BigInteger { call("multiply"); return if (mode == "replace") replacement else super.multiply(other) }
    override fun add(other: BigInteger): BigInteger { call("add"); return if (mode == "replace") replacement else super.add(other) }
    override fun shiftRight(n: Int): BigInteger { call("right"); return if (mode == "replace") replacement else super.shiftRight(n) }
    override fun shiftLeft(n: Int): BigInteger { call("left"); return if (mode == "replace") replacement else super.shiftLeft(n) }
    fun inheritedRoot(): BigInteger = super.sqrt()
    fun inheritedPair(): Array<BigInteger> = super.sqrtAndRemainder()
}
fun outcome(text: String, op: String, mode: String): String {
    val trace = StringBuilder()
    val source = Probe(text, trace, mode)
    return try {
        val values = if (op == "sqrt") arrayOf(source.inheritedRoot()) else source.inheritedPair()
        val calls = trace.toString()
        values.joinToString("|") { value ->
            val valueText = if (value === source) text else value.toString()
            "$valueText:${value === source}:${value === BigInteger.ZERO}:${value === BigInteger.ONE}:${value === BigInteger.TWO}:${value::class == BigInteger::class}"
        } + "|same=${values.size == 2 && values[0] === values[1]}|$calls"
    } catch (e: Exception) { "!${e.javaClass.simpleName}:${e.message}|$trace" }
}
val rows = mutableListOf<List<String>>()
fun record(text: String, family: String, configs: List<String> = listOf("delegate")) {
    for (op in listOf("sqrt", "pair")) for (mode in configs)
        rows += listOf(text, op, mode, family, outcome(text, op, mode))
}
val modes = listOf("delegate", "throw", "replace", "empty-pair")
for (text in listOf("-4", "-1", "0", "1", "2", "3", "4", "7", "8", "9", "10", "15", "16", "17", "18446744073709551617")) record(text, "dispatch", modes)
for (n in 0L..64L) for (delta in -1L..1L) record((n * n + delta).toString(), "small-squares")
for (bits in listOf(15,16,29,30,31,32,59,60,61,63,64,65,127,128,129,255,256,257,511,512,513,1023,1024,1025,2048,4096)) {
    val power = BigInteger.ONE.shiftLeft(bits)
    for (offset in -1L..1L) {
        val n = power.add(BigInteger.valueOf(offset))
        val square = n.multiply(n)
        for (delta in -1L..1L) record(square.add(BigInteger.valueOf(delta)).toString(), "bits-$bits")
    }
}
val source = buildString {
    appendLine("// SPDX-License-Identifier: Apache-2.0")
    appendLine("// Generated by scripts/generate-integer-sqrt-oracle.main.kts; JDK 25.0.4+9.")
    appendLine("package io.heapy.krogu.math")
    val chunks = rows.chunked(30)
    appendLine("internal fun jdk25IntegerSqrtCases(): List<Array<String>> = buildList {")
    for (index in chunks.indices) appendLine("    addAll(integerSqrtBatch$index())")
    appendLine("}")
    for ((index, chunk) in chunks.withIndex()) {
        appendLine("private fun integerSqrtBatch$index(): List<Array<String>> = listOf(")
        for (row in chunk) appendLine("    arrayOf(${row.joinToString(", ") { "\"$it\"" }}),")
        appendLine(")")
    }
}
val target = File("test/io/heapy/krogu/math/Jdk25IntegerSqrtResults.kt")
if ("--check" in args) check(target.exists() && target.readText() == source) { "Integer square-root oracle differs" }
else target.writeText(source)
println("${if ("--check" in args) "Verified" else "Generated"} ${rows.size} integer square-root cases")
