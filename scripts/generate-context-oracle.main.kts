/** Public JDK MathContext grammar oracle. Usage: [--check]. */
import java.io.File
import java.math.MathContext
import java.math.RoundingMode

check(Runtime.version().toString() in listOf("25.0.4+9", "25.0.4+9-LTS")) { "Requires JDK 25.0.4+9" }
check(args.all { it == "--check" }) { "Usage: generate-context-oracle.main.kts [--check]" }
fun outcome(text: String): String = try {
    val context = MathContext(text)
    "OK:${context.precision}:${context.roundingMode.name}"
} catch (e: IllegalArgumentException) {
    check(e.javaClass == IllegalArgumentException::class.java && e.cause == null)
    "ERR:${e.message}"
}
for (code in 0..65535) {
    val char = code.toChar()
    val digit = Character.digit(char, 10)
    check(outcome("precision=$char roundingMode=UP") == if (digit >= 0) "OK:$digit:UP" else "ERR:bad string format")
    check(outcome("precision=1${char}2 roundingMode=UP") == if (digit >= 0) "OK:${102 + digit * 10}:UP" else "ERR:bad string format")
    check(outcome("precision=1${char}roundingMode=UP") == if (char == ' ') "OK:1:UP" else "ERR:bad string format")
}
val precisions = listOf("", "+", "-", "0", "+0", "-0", "1", "-1", "7", "0007", "+0007", "-0007",
    "2147483646", "2147483647", "2147483648", "2147483649", "-2147483647", "-2147483648", "-2147483649",
    "0002147483647", "-0002147483648", "999999999999999999999", "١٢٣", "１２３", "1٢３", "٠", "-٠",
    "1.0", "1e0", "0x10", "1_0", "1 0", " 7", "7 ", "\t7", "7\n", "++7", "--7", "+-7", "−7", "²", "𝟙")
val modes = RoundingMode.entries.map { it.name } + listOf("", "up", "Up", "UNKNOWN", "UP ", " UP", "UP\n", "UP\u0000", "HALF__UP")
val inputs = linkedSetOf<String>()
for (precision in precisions) for (mode in modes) inputs += "precision=$precision roundingMode=$mode"
val canonical = "precision=7 roundingMode=HALF_EVEN"
for (index in canonical.indices) {
    inputs += canonical.removeRange(index, index + 1)
    for (char in listOf(' ', '\t', '\n', '\r', '\u0000', '\u00a0', '=', '+', '-', '0', 'x'))
        inputs += canonical.replaceRange(index, index + 1, char.toString())
}
for (size in listOf(10000, 1000000)) for (token in listOf("0".repeat(size) + "7", "9".repeat(size))) {
    val result = outcome("precision=$token roundingMode=UP")
    check(result == if (token[0] == '0') "OK:7:UP" else "ERR:bad string format")
}
fun hex(text: String) = text.toCharArray().joinToString("") { it.code.toString(16).padStart(4, '0') }
val rows = inputs.map { "${hex(it)}|${outcome(it)}" }
val source = buildString {
    appendLine("// SPDX-License-Identifier: Apache-2.0")
    appendLine("// Generated by scripts/generate-context-oracle.main.kts; JDK 25.0.4+9.")
    appendLine("package io.heapy.krogu.math")
    appendLine("internal fun jdk25ContextResults(): Sequence<String> = sequence {")
    for (chunk in rows.chunked(100)) {
        appendLine("    yieldAll(\"\"\"")
        chunk.forEach { appendLine(it) }
        appendLine("\"\"\".trim().lineSequence())")
    }
    appendLine("}")
}
val target = File("test/io/heapy/krogu/math/Jdk25ContextResults.kt")
if ("--check" in args) check(target.readText() == source) { "MathContext oracle is stale" }
else target.writeText(source)
println("Verified 196608 BMP grammar cases, ${rows.size} compound cases and four long inputs.")
