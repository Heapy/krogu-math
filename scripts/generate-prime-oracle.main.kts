/** Primality/prime-successor outcomes from public JDK APIs. Usage: [--check]. */
import java.io.File
import java.math.BigInteger
import java.util.Random

check(Runtime.version().toString() in listOf("25.0.4+9", "25.0.4+9-LTS")) { "Requires JDK 25.0.4+9" }
check(args.all { it == "--check" })
val rows = mutableListOf<List<String>>()
fun record(op: String, n: BigInteger, certainty: Int, action: () -> Any?) {
    val result = try { action().toString() } catch (e: Exception) { "!${e.javaClass.simpleName}" }
    rows += listOf(op, n.toString(), certainty.toString(), result)
}
val primes = listOf("2", "3", "5", "47", "53", "2147483647", "2305843009213693951", "18446744073709551557").map(::BigInteger) +
    listOf(65, 77, 78, 80, 81).map { BigInteger.probablePrime(it, Random(it.toLong())) }
for (prime in primes) for (n in listOf(prime, prime.negate())) for (certainty in listOf(Int.MIN_VALUE, -1, 0, 1, 2, 31, 100, Int.MAX_VALUE))
    record("prime", n, certainty) { n.isProbablePrime(certainty) }
val composites = listOf("0", "1", "4", "49", "561", "1105", "1729", "2047", "1373653", "25326001", "3215031751",
    "2152302898747", "3474749660383", "341550071728321", "3825123056546413051", "318665857834031151167461", "3317044064679887385961981")
for (text in composites) for (n in listOf(BigInteger(text), BigInteger(text).negate())) for (certainty in listOf(-1, 0, 100, Int.MAX_VALUE))
    record("prime", n, certainty) { n.isProbablePrime(certainty) }
for (n in listOf("618970019642690137449562111", "170141183460469231731687303715884105727").map(::BigInteger))
    record("prime", n, 100) { n.isProbablePrime(100) }
for (text in composites + listOf("2", "47", "18446744073709551557", "3317044064679887385961980", "3317044064679887385961982")) {
    val n = BigInteger(text)
    record("next", n, 0) { n.nextProbablePrime() }
}
for (bits in listOf(81, 82, 83, 89, 127, 255, 256)) for (delta in -2L..2L) {
    val n = BigInteger.ONE.shiftLeft(bits).add(BigInteger.valueOf(delta))
    record("next", n, 0) { n.nextProbablePrime() }
}
val factorial = (2L..64L).fold(BigInteger.ONE) { n, factor -> n.multiply(BigInteger.valueOf(factor)) }
record("next", factorial.add(BigInteger.ONE), 0) { factorial.add(BigInteger.ONE).nextProbablePrime() }
for (text in listOf("-1", "-100", "-170141183460469231731687303715884105727", "0", "1", "2", "3", "47", "53", "100",
    "3317044064679887385961981", "170141183460469231731687303715884105727")) {
    record("nextTrace", BigInteger(text), 0) {
        val calls = mutableListOf<String>()
        val observed = object : BigInteger(text) {
            override fun compareTo(other: BigInteger): Int { calls += "compareTo"; return super.compareTo(other) }
            override fun add(other: BigInteger): BigInteger { calls += "add"; return super.add(other) }
            override fun setBit(bit: Int): BigInteger { calls += "setBit"; return super.setBit(bit) }
            override fun isProbablePrime(certainty: Int): Boolean { calls += "prime:$certainty"; return super.isProbablePrime(certainty) }
            override fun bitLength(): Int { calls += "bitLength"; return super.bitLength() }
            override fun signum(): Int { calls += "signum"; return super.signum() }
            override fun abs(): BigInteger { calls += "abs"; return super.abs() }
            override fun toByte(): Byte = toInt().toByte()
            override fun toShort(): Short = toInt().toShort()
        }
        val result = try { observed.nextProbablePrime().toString() }
            catch (e: Exception) { "!${e.javaClass.simpleName}:${e.message}" }
        "$result|${calls.joinToString(",")}"
    }
}
val source = buildString {
    appendLine("// SPDX-License-Identifier: Apache-2.0")
    appendLine("// Generated by scripts/generate-prime-oracle.main.kts; JDK 25.0.4+9.")
    appendLine("package io.heapy.krogu.math")
    appendLine("internal fun jdk25PrimeCases(): List<Array<String>> = listOf(")
    for (row in rows) appendLine("    arrayOf(${row.joinToString(", ") { "\"$it\"" }}),")
    appendLine(")")
}
val target = File("test/io/heapy/krogu/math/Jdk25PrimeResults.kt")
if ("--check" in args) {
    check(target.exists() && target.readText() == source) { "Prime oracle differs" }
    println("Verified ${rows.size} prime/next-prime outcomes")
} else {
    target.parentFile.mkdirs(); target.writeText(source)
    println("Generated ${rows.size} prime/next-prime outcomes")
}
