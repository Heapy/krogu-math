/** Integer power callback/value/identity observations from public JDK APIs. Usage: [--check]. */
import java.io.File
import java.lang.management.ManagementFactory
import java.math.BigInteger

check(Runtime.version().toString() in listOf("25.0.4+9", "25.0.4+9-LTS")) { "Requires JDK 25.0.4+9" }
check("-XX:-OmitStackTraceInFastThrow" in ManagementFactory.getRuntimeMXBean().inputArguments) {
    "Requires JAVA_TOOL_OPTIONS=-XX:-OmitStackTraceInFastThrow for exact diagnostics"
}
check(args.all { it == "--check" })
class Probe(text: String, val trace: StringBuilder, val mode: String) : BigInteger(text) {
    private fun call(name: String) {
        trace.append("$name;")
        if (mode == "$name:throw") throw IllegalStateException("$name callback")
    }
    private fun replacement(name: String): BigInteger? =
        if (mode.startsWith("$name:") && mode != "$name:throw") BigInteger(mode.substringAfter(':')) else null
    override fun toByte(): Byte = super.toInt().toByte()
    override fun toShort(): Short = super.toInt().toShort()
    override fun equals(other: Any?): Boolean { call("equals"); return when (mode) {
        "equals:true" -> true; "equals:false" -> false; else -> super.equals(other)
    } }
    override fun abs(): BigInteger { call("abs"); return if (mode == "self") this else replacement("abs") ?: super.abs() }
    override fun negate(): BigInteger { call("negate"); return replacement("negate") ?: super.negate() }
    override fun multiply(other: BigInteger): BigInteger { call("multiply"); return super.multiply(other) }
    override fun signum(): Int { call("signum"); return super.signum() }
    override fun toLong(): Long { call("long"); return super.toLong() }
    override fun getLowestSetBit(): Int { call("lowest"); return if (mode.startsWith("lowest:") && mode != "lowest:throw") mode.substringAfter(':').toInt() else super.getLowestSetBit() }
    override fun bitLength(): Int { call("bits"); return if (mode.startsWith("bits:") && mode != "bits:throw") mode.substringAfter(':').toInt() else super.bitLength() }
    override fun shiftRight(n: Int): BigInteger { call("right($n)"); if (mode == "right:throw") throw IllegalStateException("right callback"); return replacement("right") ?: super.shiftRight(n) }
    override fun shiftLeft(n: Int): BigInteger { call("left($n)"); if (mode == "left:throw") throw IllegalStateException("left callback"); return super.shiftLeft(n) }
}
fun outcome(text: String, exponent: Int, mode: String): String {
    val trace = StringBuilder()
    val source = Probe(text, trace, mode)
    return try {
        val value = source.pow(exponent)
        val calls = trace.toString()
        val result = if (value === source) text else value.toString()
        "$result|${value === source}|${value === BigInteger.ZERO}|${value === BigInteger.ONE}|${value === BigInteger.TWO}|${value === BigInteger.TEN}|${value::class == BigInteger::class}|$calls"
    } catch (e: Exception) { "!${e.javaClass.simpleName}:${e.message}|$trace" }
}
val modes = listOf("delegate", "self", "equals:true", "equals:false") +
    listOf("equals", "abs", "negate", "lowest", "right", "bits", "multiply", "signum", "long", "left").map { "$it:throw" } +
    listOf("abs:0", "abs:1", "abs:3", "abs:-3", "negate:3", "lowest:-1", "lowest:0", "lowest:1", "lowest:31", "lowest:2147483647",
        "bits:-1", "bits:0", "bits:1", "bits:2", "bits:21", "bits:22", "bits:31", "bits:32", "bits:33", "bits:63", "bits:2147483647",
        "right:0", "right:1", "right:3", "right:-3")
val inputs = listOf("0", "1", "-1", "2", "-2", "3", "-3", "6", "-6", "65535", "2147483649", "4294967299", "36893488160304005125")
val exponents = listOf(Int.MIN_VALUE, -1, 0, 1, 2, 3, 4, 5, 17, 31, 32, 33, Int.MAX_VALUE)
val rows = mutableListOf<List<String>>()
for (text in inputs) for (exponent in exponents) for (mode in modes)
    rows += listOf(text, exponent.toString(), mode, outcome(text, exponent, mode))
for (bits in listOf(1073741823, 1073741824, 1073741825)) for (e in listOf(2, 3))
    rows += listOf("3", e.toString(), "bits:$bits", outcome("3", e, "bits:$bits"))
for (prefix in listOf(2L, 4L, 6L, 8L, 12L)) for (e in listOf(31, 32, 33, 63, 64, 65, 127, Int.MAX_VALUE)) {
    val text = BigInteger.valueOf(prefix).shiftLeft(64).add(BigInteger.valueOf(5)).toString()
    for (mode in listOf("bits:0", "bits:-1")) rows += listOf(text, e.toString(), mode, outcome(text, e, mode))
}
val source = buildString {
    appendLine("// SPDX-License-Identifier: Apache-2.0")
    appendLine("// Generated by scripts/generate-integer-pow-oracle.main.kts; JDK 25.0.4+9.")
    appendLine("package io.heapy.krogu.math")
    val chunks = rows.chunked(40)
    appendLine("internal fun jdk25IntegerPowCases(): List<Array<String>> = buildList {")
    for (index in chunks.indices) appendLine("    addAll(integerPowBatch$index())")
    appendLine("}")
    for ((index, chunk) in chunks.withIndex()) {
        appendLine("private fun integerPowBatch$index(): List<Array<String>> = listOf(")
        for (row in chunk) appendLine("    arrayOf(${row.joinToString(", ") { "\"$it\"" }}),")
        appendLine(")")
    }
}
val target = File("src/commonTest/kotlin/io/heapy/krogu/math/Jdk25IntegerPowResults.kt")
if ("--check" in args) check(target.exists() && target.readText() == source) { "Integer power oracle differs" }
else target.writeText(source)
println("${if ("--check" in args) "Verified" else "Generated"} ${rows.size} integer power cases")
