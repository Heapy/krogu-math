/** Public JDK null/invalid-argument precedence. Run from repo root, optionally --check. */
import java.io.File
import java.math.BigInteger as JI
import java.math.BigDecimal as JD
import java.math.MathContext as JC
import java.math.RoundingMode as JR

check(Runtime.version().toString() in listOf("25.0.4+9", "25.0.4+9-LTS")) { "Requires JDK 25.0.4+9" }
check(args.all { it == "--check" }) { "Usage: generate-null-oracle.main.kts [--check]" }
val integers = listOf(-3, -1, 0, 1, 2, 7, 8, 9, 31, 32, 36, 37)
val results = mutableListOf<String>()
fun record(action: () -> Any?) { results += try { action().toString() } catch (e: Exception) { "!${e.javaClass.simpleName}" } }
for (sign in integers) for (off in integers) for (len in integers)
    record { JI(sign, null, off, len) }
for (a in listOf(-10L, -1, 0, 1, 10)) for (m in listOf(-10L, -1, 0, 1, 10))
    record { JI.valueOf(a).modPow(null, JI.valueOf(m)) }
for (text in listOf("", "-", "1.0", "1E+", "NaN", "0", "1", "-1", "UP", "HALF_EVEN", "precision=7 roundingMode=UP"))
    record { JD(text, null as JC?) }
for (d in listOf(Double.NaN, Double.NEGATIVE_INFINITY, Double.POSITIVE_INFINITY, -0.0, 0.0, 0.1, 1.0))
    record { JD(d, null as JC?) }
for (text in listOf("", "0", ".", "1.00")) record { JD(text.toCharArray(), null as JC?) }
for (text in listOf("", "0", ".", "1.00")) for (off in integers) for (len in integers)
    record { JD(text.toCharArray(), off, len, null) }
val decimals = listOf("-10.00", "-1.01", "0", "0.00", "1", "1.00", "10.10")
for (text in decimals) record { JD(text).sqrt(null) }
@Suppress("DEPRECATION")
fun legacyDivisions() {
    for (text in decimals) for (mode in integers) record { JD(text).divide(null, mode) }
    for (text in decimals) for (scale in integers) for (mode in integers) record { JD(text).divide(null, scale, mode) }
}
legacyDivisions()
for (precision in integers) record { JC(precision, null as JR?) }
check(results.size == 3462)
val chunks = results.chunked(500)
val source = buildString {
    appendLine("// SPDX-License-Identifier: Apache-2.0")
    appendLine("// Generated by scripts/generate-null-oracle.main.kts; JDK 25.0.4+9.")
    appendLine("// ${results.size} exact null/invalid-argument outcomes; do not edit.")
    appendLine("package io.heapy.krogu.math")
    appendLine("internal fun nullPrecedenceExpected(): Sequence<String> = sequenceOf(")
    for (i in chunks.indices) appendLine("    nullExpectedChunk$i(),")
    appendLine(").flatMap { it.lineSequence() }")
    for ((i, chunk) in chunks.withIndex()) {
        val literal = chunk.joinToString("\\n")
        check('"' !in literal && '$' !in literal && literal.toByteArray().size < 60000)
        appendLine("private fun nullExpectedChunk$i(): String = \"$literal\"")
    }
}
val target = File("src/commonTest/kotlin/io/heapy/krogu/math/Jdk25NullPrecedenceResults.kt")
if ("--check" in args) {
    check(target.exists() && target.readText() == source) { "Null precedence oracle differs" }
    println("Verified ${results.size} null/invalid-argument outcomes")
} else {
    target.parentFile.mkdirs(); target.writeText(source)
    println("Generated ${results.size} null/invalid-argument outcomes")
}
