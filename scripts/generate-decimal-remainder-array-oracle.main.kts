/** Public-JDK remainder behavior for replacement pair arrays. Usage: [--check]. */
import java.math.BigDecimal
import java.math.MathContext
import java.io.File
check(Runtime.version().toString() in listOf("25.0.4+9", "25.0.4+9-LTS"))
check(args.all { it == "--check" })
class ArrayProbe(text: String, val length: Int, val trace: StringBuilder) : BigDecimal(text) {
    override fun toByte(): Byte = super.toInt().toByte()
    override fun toShort(): Short = super.toInt().toShort()
    private fun pair(): Array<BigDecimal> = Array(length) { if (it == 1) this else BigDecimal("7.0") }
    override fun divideAndRemainder(v: BigDecimal?): Array<BigDecimal> {
        trace.append("pair(${v == null});"); return pair()
    }
    override fun divideAndRemainder(v: BigDecimal?, mc: MathContext?): Array<BigDecimal> {
        trace.append("pair(${v == null},${mc?.precision});"); return pair()
    }
    fun enter(op: String, v: BigDecimal?, mc: MathContext?): BigDecimal =
        if (op == "exact") super.remainder(v) else super.remainder(v, mc)
}
fun arrayOutcome(text: String, length: Int, op: String, operand: String, precision: Int): String {
    val trace = StringBuilder()
    val source = ArrayProbe(text, length, trace)
    val divisor = when (operand) { "null" -> null; "self" -> source; else -> BigDecimal("2.0") }
    val mc = if (precision < 0) null else MathContext(precision)
    return try {
        val result = source.enter(op, divisor, mc)
        val calls = trace.toString()
        "${if (result === source) "source" else result.toString()}|$calls"
    } catch (e: Exception) { "!${e::class.simpleName}:${e.message}|$trace" }
}
val rows = mutableListOf<List<String>>()
for (text in listOf("0.00", "10.50", "-10.50")) for (length in 0..3)
    for (op in listOf("exact", "context")) for (operand in listOf("null", "self", "other"))
        for (precision in listOf(-1, 0, 2))
            rows += listOf(text, length.toString(), op, operand, precision.toString(), arrayOutcome(text, length, op, operand, precision))
val generated = buildString {
    appendLine("// SPDX-License-Identifier: Apache-2.0")
    appendLine("// Generated by scripts/generate-decimal-remainder-array-oracle.main.kts; JDK 25.0.4+9.")
    appendLine("package io.heapy.krogu.math")
    appendLine("internal fun jdk25DecimalRemainderArrayCases(): List<Array<String>> = listOf(")
    for (chunk in rows.chunked(100)) {
        appendLine("    \"\"\"")
        for (row in chunk) appendLine(row.joinToString("\t"))
        appendLine("    \"\"\".trimIndent(),")
    }
    appendLine(").flatMap { it.lines().map { line -> line.split('\\t').toTypedArray() } }")
}
val target = File("test/io/heapy/krogu/math/Jdk25DecimalRemainderArrayResults.kt")
if ("--check" in args) check(target.exists() && target.readText() == generated) { "Remainder array oracle differs" }
else target.writeText(generated)
println("${if ("--check" in args) "Verified" else "Generated"} ${rows.size} decimal remainder array cases")
