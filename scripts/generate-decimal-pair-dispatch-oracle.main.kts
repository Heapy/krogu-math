/** Public-JDK composition of integral quotient, product, subtraction and remainder. Usage: [--check]. */
import java.math.BigDecimal
import java.math.MathContext
import java.math.RoundingMode
import java.io.File
check(Runtime.version().toString() in listOf("25.0.4+9", "25.0.4+9-LTS"))
check(args.all { it == "--check" })

class PairQuotient(val trace: StringBuilder, val mode: String, val original: BigDecimal) : BigDecimal("3.0") {
    override fun toByte(): Byte = super.toInt().toByte()
    override fun toShort(): Short = super.toInt().toShort()
    override fun multiply(v: BigDecimal): BigDecimal {
        trace.append("multiply;")
        return when (mode) {
            "multiply-throw" -> throw IllegalStateException("multiply callback")
            "multiply-source" -> original
            "multiply-divisor" -> v
            else -> super.multiply(v)
        }
    }
}
class PairSource(text: String, val trace: StringBuilder, val mode: String) : BigDecimal(text) {
    override fun toByte(): Byte = super.toInt().toByte()
    override fun toShort(): Short = super.toInt().toShort()
    private fun quotient(): BigDecimal {
        if (mode == "integral-throw") throw IllegalStateException("integral callback")
        return PairQuotient(trace, mode, this)
    }
    override fun divideToIntegralValue(v: BigDecimal): BigDecimal {
        trace.append("integral;")
        return quotient()
    }
    override fun divideToIntegralValue(v: BigDecimal, mc: MathContext): BigDecimal {
        trace.append("integral(${mc.precision},${mc.roundingMode});")
        return quotient()
    }
    override fun divideAndRemainder(v: BigDecimal): Array<BigDecimal> {
        trace.append("pair;")
        if (mode == "pair-throw") throw IllegalStateException("pair callback")
        if (mode == "pair-replace") return arrayOf(BigDecimal("7.0"), this)
        return super.divideAndRemainder(v)
    }
    override fun divideAndRemainder(v: BigDecimal, mc: MathContext): Array<BigDecimal> {
        trace.append("pair(${mc.precision},${mc.roundingMode});")
        if (mode == "pair-throw") throw IllegalStateException("pair callback")
        if (mode == "pair-replace") return arrayOf(BigDecimal("7.0"), this)
        return super.divideAndRemainder(v, mc)
    }
    override fun subtract(v: BigDecimal): BigDecimal {
        trace.append("subtract(${if (v === this) "source" else v.toString()});")
        return when (mode) {
            "subtract-throw" -> throw IllegalStateException("subtract callback")
            "subtract-source" -> this
            "subtract-product" -> v
            else -> super.subtract(v)
        }
    }
    fun enter(op: String, v: BigDecimal, mc: MathContext): Array<BigDecimal> = when (op) {
        "pair" -> super.divideAndRemainder(v)
        "pair-context" -> super.divideAndRemainder(v, mc)
        "remainder" -> arrayOf(super.remainder(v))
        else -> arrayOf(super.remainder(v, mc))
    }
}
fun pairOutcome(text: String, divisor: String, mode: String, op: String, precision: Int, rounding: String): String {
    val trace = StringBuilder()
    val source = PairSource(text, trace, mode)
    val operand = BigDecimal(divisor)
    return try {
        val result = source.enter(op, operand, MathContext(precision, RoundingMode.valueOf(rounding)))
        val calls = trace.toString()
        result.joinToString(",") {
            "${it.toString()}:${it.scale()}:${when { it === source -> "source"; it === operand -> "divisor"; it is PairQuotient -> "quotient"; else -> "base" }}"
        } + "|" + calls
    } catch (e: Exception) { "!${e::class.simpleName}:${e.message}|$trace" }
}
val rows = mutableListOf<List<String>>()
for (text in listOf("0.00", "10.50", "-1000", "1E+4"))
    for (divisor in listOf("0.0", "-2.00", "1E+3"))
        for (mode in listOf("delegate", "integral-throw", "pair-throw", "pair-replace", "multiply-throw", "multiply-source", "multiply-divisor", "subtract-throw", "subtract-source", "subtract-product"))
            for (op in listOf("pair", "pair-context", "remainder", "remainder-context"))
                for ((precision, rounding) in listOf(0 to "HALF_UP", 2 to "UNNECESSARY", 7 to "FLOOR")) {
                    rows += listOf(text, divisor, mode, op, precision.toString(), rounding, pairOutcome(text, divisor, mode, op, precision, rounding))
                }
val generated = buildString {
    appendLine("// SPDX-License-Identifier: Apache-2.0")
    appendLine("// Generated by scripts/generate-decimal-pair-dispatch-oracle.main.kts; JDK 25.0.4+9.")
    appendLine("package io.heapy.krogu.math")
    appendLine("internal fun jdk25DecimalPairDispatchCases(): List<Array<String>> = listOf(")
    for (chunk in rows.chunked(100)) {
        appendLine("    \"\"\"")
        for (row in chunk) appendLine(row.joinToString("\t"))
        appendLine("    \"\"\".trimIndent(),")
    }
    appendLine(").flatMap { it.lines().map { line -> line.split('\\t').toTypedArray() } }")
}
val target = File("test/io/heapy/krogu/math/Jdk25DecimalPairDispatchResults.kt")
if ("--check" in args) check(target.exists() && target.readText() == generated) { "Decimal pair dispatch oracle differs" }
else target.writeText(generated)
println("${if ("--check" in args) "Verified" else "Generated"} ${rows.size} decimal pair dispatch cases")
