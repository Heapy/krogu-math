/** Truthful context-division controls projected from every frozen dispatch row. Usage: [--check]. */
import java.io.File
import java.math.BigDecimal
import java.math.BigInteger
import java.math.MathContext
import java.math.RoundingMode
import java.security.MessageDigest

check(Runtime.version().toString() in listOf("25.0.4+9", "25.0.4+9-LTS"))
check(args.all { it == "--check" })
val source = File("src/commonTest/kotlin/io/heapy/krogu/math/Jdk25DecimalContextDispatchResults.kt")
val sourceBytes = source.readBytes()
val sourceHash = MessageDigest.getInstance("SHA-256").digest(sourceBytes).joinToString("") { "%02x".format(it) }
check(sourceHash == "88fc3c5bc8277a048a83a9ad9b6546bd8a23ae1ad9a10126409d857367391026") {
    "Frozen dispatch data changed; review the contract projection before updating its provenance"
}
val frozenRows = sourceBytes.toString(Charsets.UTF_8).lineSequence()
    .filter { '\t' in it }.map { it.split('\t') }.toList()
check(frozenRows.size == 75728 && frozenRows.all { it.size == 7 })
// LinkedHashSet keeps first-occurrence order. No old result or callback mode becomes a control expectation.
val inputs = frozenRows.map { row ->
    val topology = when (row[3]) { "self", "null" -> row[3]; else -> "ordinary" }
    listOf(row[0], row[1], topology, row[4], row[5])
}.toCollection(linkedSetOf())
check(inputs.isNotEmpty())

class TruthfulDecimal(text: String) : BigDecimal(text) {
    override fun toByte(): Byte = super.toInt().toByte()
    override fun toShort(): Short = super.toInt().toShort()
    override fun signum(): Int = super.signum()
    override fun precision(): Int = super.precision()
    override fun scale(): Int = super.scale()
    override fun unscaledValue(): BigInteger = super.unscaledValue()
    override fun abs(): BigDecimal = super.abs()
    override fun abs(mc: MathContext?): BigDecimal = super.abs(mc)
    override fun negate(): BigDecimal = super.negate()
    override fun negate(mc: MathContext?): BigDecimal = super.negate(mc)
    override fun divide(divisor: BigDecimal?): BigDecimal = super.divide(divisor)
    override fun divide(divisor: BigDecimal?, mc: MathContext?): BigDecimal = super.divide(divisor, mc)
}
fun outcome(input: List<String>, mask: Int): String {
    val a: BigDecimal = if (mask and 1 == 0) BigDecimal(input[0]) else TruthfulDecimal(input[0])
    val b: BigDecimal? = when (input[2]) {
        "self" -> a
        "null" -> null
        "ordinary" -> if (mask and 2 == 0) BigDecimal(input[1]) else TruthfulDecimal(input[1])
        else -> error("Unknown topology")
    }
    val p = input[3].toInt()
    val mc = if (p < 0) null else MathContext(p, RoundingMode.valueOf(input[4]))
    return try {
        val result = a.divide(b, mc)
        "${result.unscaledValue()}@${result.scale()}"
    } catch (_: ArithmeticException) { "!ArithmeticException" }
      catch (_: NullPointerException) { "!NullPointerException" }
}
var observations = 0
val rows = inputs.map { input ->
    val expected = outcome(input, 0)
    for (mask in if (input[2] == "ordinary") 0..3 else 0..1) {
        check(outcome(input, mask) == expected) { "Truthful JDK subclass disagrees: $input mask=$mask" }
        observations++
    }
    input + expected
}
val generated = buildString {
    appendLine("// SPDX-License-Identifier: Apache-2.0")
    appendLine("// Generated by scripts/generate-decimal-context-contract-oracle.main.kts; JDK 25.0.4+9.")
    appendLine("// Projection source SHA-256: $sourceHash")
    appendLine("// Fields: source, divisor, topology, context precision (-1 = null), rounding, coefficient@scale or exception type.")
    appendLine("package io.heapy.krogu.math")
    appendLine("internal fun jdk25DecimalContextContractCases(): List<Array<String>> = listOf(")
    for (chunk in rows.chunked(100)) {
        appendLine("    \"\"\"")
        for (row in chunk) appendLine(row.joinToString("\t"))
        appendLine("    \"\"\".trimIndent(),")
    }
    appendLine(").flatMap { it.lines().map { line -> line.split('\\t').toTypedArray() } }")
}
val target = File("src/commonTest/kotlin/io/heapy/krogu/math/Jdk25DecimalContextContractResults.kt")
if ("--check" in args) check(target.exists() && target.readText() == generated) { "Context contract oracle differs" }
else target.writeText(generated)
println("${if ("--check" in args) "Verified" else "Generated"} ${rows.size} distinct controls from ${frozenRows.size} frozen rows; $observations JDK ordinary/truthful checks")
println("Topology counts: ${rows.groupingBy { it[2] }.eachCount()}; precision counts: ${rows.groupingBy { it[3] }.eachCount()}")
println("Outcome counts: ${rows.groupingBy { if (it[5].startsWith('!')) it[5] else "value" }.eachCount()}")
