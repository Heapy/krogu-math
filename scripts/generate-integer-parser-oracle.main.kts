/** String constructor values and diagnostics from public JDK APIs. Usage: [--check]. */
import java.io.File
import java.math.BigInteger

check(Runtime.version().toString() in listOf("25.0.4+9", "25.0.4+9-LTS")) { "Requires JDK 25.0.4+9" }
check(args.all { it == "--check" })
val inputs = linkedSetOf<Pair<Int, String>>()
val basic = listOf("", "+", "-", "++1", "--1", "+-1", "-+1", "1+2", "1-2", "x+1", "x-1",
    "0+", "000-", " 1", "1 ", "\t1", "1\n", "\u0000", "\"", "\\", "$", "!", "0", "-0", "+0",
    "000", "٠０0", "٠٠!", "000١٢!", "١٢٣", "１２３", "\uD835\uDFCE", "\uD800", "\uDC00", "z", "Z")
for (radix in listOf(Int.MIN_VALUE, -1, 0, 1) + (2..37) + listOf(Int.MAX_VALUE))
    for (text in basic) inputs += radix to text
for (radix in 2..36) {
    var power = radix.toLong()
    var width = 1
    while (power * radix <= Int.MAX_VALUE) { power *= radix; width++ }
    for (length in listOf(width - 1, width, width + 1, 2 * width, 2 * width + 1, 3 * width + 1)) {
        val positions = listOf(0, 1, width - 1, width, width + 1, length - 1).filter { it in 0 until length }.distinct()
        for (position in positions) for (prefix in listOf("", "-", "+000", "٠０")) {
            val text = "1".repeat(position) + "!" + "1".repeat(length - position - 1)
            inputs += radix to prefix + text
            // Embedded signs must win even when an invalid digit occurs earlier.
            inputs += radix to prefix + text + "+"
        }
        for (prefix in listOf("", "+", "-000", "٠０")) inputs += radix to prefix + "1".repeat(length)
    }
}
fun outcome(text: String, radix: Int): String = try {
    BigInteger(text, radix).toString()
} catch (e: NumberFormatException) { "!NumberFormatException:${e.message}" }
fun quoted(text: String): String = "\"" + text.map { ch ->
    if (ch in ' '..'~' && ch != '\\' && ch != '"' && ch != '$') ch.toString()
    else "\\u" + ch.code.toString(16).padStart(4, '0')
}.joinToString("") + "\""
val rows = inputs.map { (radix, text) -> listOf(radix.toString(), text, outcome(text, radix)) }
val source = buildString {
    appendLine("// SPDX-License-Identifier: Apache-2.0")
    appendLine("// Generated by scripts/generate-integer-parser-oracle.main.kts; JDK 25.0.4+9.")
    appendLine("package io.heapy.krogu.math")
    appendLine("internal fun jdk25IntegerParserCases(): List<Array<String>> = buildList {")
    val chunks = rows.chunked(40)
    for (index in chunks.indices) appendLine("    addAll(integerParserBatch$index())")
    appendLine("}")
    for ((index, chunk) in chunks.withIndex()) {
        appendLine("private fun integerParserBatch$index(): List<Array<String>> = listOf(")
        for (row in chunk) appendLine("    arrayOf(${row.joinToString(", ", transform = ::quoted)}),")
        appendLine(")")
    }
}
val target = File("src/commonTest/kotlin/io/heapy/krogu/math/Jdk25IntegerParserResults.kt")
if ("--check" in args) check(target.exists() && target.readText() == source) { "Integer parser oracle differs" }
else target.writeText(source)
println("${if ("--check" in args) "Verified" else "Generated"} ${rows.size} integer parser cases")
