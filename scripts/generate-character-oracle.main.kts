/** Exhaustive UTF-16 digit/radix oracle from public JDK APIs. Usage: [--check]. */
import java.io.File
import java.math.BigInteger
import java.math.BigDecimal

check(Runtime.version().toString() in listOf("25.0.4+9", "25.0.4+9-LTS")) { "Requires JDK 25.0.4+9" }
check(args.all { it == "--check" }) { "Usage: generate-character-oracle.main.kts [--check]" }
val digits = ByteArray(65536) { Character.digit(it.toChar(), 36).toByte() }
fun number(action: () -> Any): Int? {
    val value = try { action() } catch (e: NumberFormatException) { return null }
    return value.toString().toInt()
}
for (code in digits.indices) {
    val digit = digits[code].toInt()
    for (radix in 2..36) check(Character.digit(code.toChar(), radix) == if (digit in 0 until radix) digit else -1)
    val text = code.toChar().toString()
    check(number { BigInteger(text, 36) } == digit.takeIf { it >= 0 }) { "Integer single character U+${code.toString(16)}" }
    check(number { BigDecimal(text) } == digit.takeIf { it in 0..9 }) { "Decimal single character U+${code.toString(16)}" }
}
val ranges = mutableListOf<Triple<Int, Int, Int>>()
var code = 0
while (code < digits.size) {
    if (digits[code] < 0) { code++; continue }
    val start = code
    val first = digits[code].toInt()
    while (code < digits.size && digits[code].toInt() == first + code - start) code++
    ranges += Triple(start, code - start, first)
}
val restored = ByteArray(65536) { -1 }
for ((start, length, first) in ranges) repeat(length) { restored[start + it] = (first + it).toByte() }
check(restored.contentEquals(digits))
val supplementary = mutableListOf<Triple<Int, Int, Int>>()
for (cp in 0x10000..0x10ffff) if (Character.digit(cp, 36) >= 0) {
    val text = String(Character.toChars(cp))
    supplementary += Triple(cp, number { BigInteger(text, 36) } ?: -1, number { BigDecimal(text) } ?: -1)
}
val source = buildString {
    appendLine("// SPDX-License-Identifier: Apache-2.0")
    appendLine("// Generated by scripts/generate-character-oracle.main.kts; JDK 25.0.4+9.")
    appendLine("// Complete BMP digit map, verified for all 35 valid radices and both public string constructors.")
    appendLine("package io.heapy.krogu.math")
    appendLine("internal fun jdk25BmpDigits(): ByteArray = ByteArray(65536) { -1 }.apply {")
    for ((start, length, first) in ranges)
        appendLine("    repeat($length) { this[0x${start.toString(16)} + it] = ($first + it).toByte() }")
    appendLine("}")
    appendLine("// Supplementary characters that Character.digit(codePoint, 36) accepts; constructors use UTF-16 units.")
    appendLine("internal fun jdk25SupplementaryDigits(): IntArray = intArrayOf(")
    for ((cp, integer, decimal) in supplementary) appendLine("    0x${cp.toString(16)}, $integer, $decimal,")
    appendLine(")")
}
val target = File("src/commonTest/kotlin/io/heapy/krogu/math/Jdk25CharacterResults.kt")
if ("--check" in args) {
    check(target.exists() && target.readText() == source) { "Character oracle differs" }
    println("Verified 2293760 digit/radix pairs, 131072 BMP constructor results and ${supplementary.size} supplementary characters")
} else {
    target.parentFile.mkdirs(); target.writeText(source)
    println("Generated complete BMP map (${ranges.size} ranges) and ${supplementary.size} supplementary character results")
}
