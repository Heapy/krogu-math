/** Public-API oracle only. Run from the repository root, optionally with --check. */
import java.io.File
import java.math.BigDecimal

check(System.getProperty("java.vendor").contains("BellSoft")) { "Requires BellSoft Liberica" }
check(Runtime.version().toString() in listOf("25.0.4+9", "25.0.4+9-LTS")) { "Requires JDK 25.0.4+9" }
check(args.all { it == "--check" }) { "Usage: generate-canonical-double-oracle.main.kts [--check]" }
val inputs = linkedSetOf<Long>()
fun neighbors(bits: Long) {
    for (offset in -1L..1L) {
        val magnitude = bits + offset
        if (magnitude in 1L..0x7fefffffffffffffL) {
            inputs += magnitude
            inputs += magnitude or Long.MIN_VALUE
        }
    }
}
// Every finite binary power, including all 52 subnormal powers, and adjacent raw bits.
for (exponent in 1L..2046L) neighbors(exponent shl 52)
for (bit in 0..51) neighbors(1L shl bit)
for (bits in 1L..128L) neighbors(bits)
// Every finite power of ten: covers decimal exponent carries and notation boundaries.
for (exponent in -323..308) neighbors(java.lang.Double.parseDouble("1e$exponent").toRawBits())
neighbors(0x7fefffffffffffffL)
inputs += 0L
inputs += Long.MIN_VALUE
val rows = inputs.map { bits ->
    val d = Double.fromBits(bits)
    val decimal = BigDecimal.valueOf(d)
    "$bits|${decimal.unscaledValue()}|${decimal.scale()}|${java.lang.Double.toString(d)}"
}
val source = buildString {
    appendLine("// SPDX-License-Identifier: Apache-2.0")
    appendLine("// Generated by scripts/generate-canonical-double-oracle.main.kts; public Liberica 25.0.4+9 APIs.")
    appendLine("package io.heapy.krogu.math")
    appendLine("internal const val CANONICAL_DOUBLE_CASES = ${rows.size}")
    appendLine("internal fun canonicalDoubleRows(): Sequence<String> = sequence {")
    for (chunk in rows.chunked(200)) {
        appendLine("    yieldAll(\"\"\"")
        chunk.forEach { appendLine(it) }
        appendLine("\"\"\".trim().lineSequence())")
    }
    appendLine("}")
}
val target = File("src/commonTest/kotlin/io/heapy/krogu/math/CanonicalDoubleOracleData.kt")
if ("--check" in args) check(target.readText() == source) { "Canonical Double oracle is stale" }
else target.writeText(source)
println("Verified ${rows.size} exact coefficient/scale/text outcomes on ${System.getProperty("java.vendor")} ${Runtime.version()}.")
