/** Persist exact JDK outputs for the structured signed-scale-boundary corpus.
 * Usage: kotlinr scripts/generate-scale-oracle.main.kts [--check]
 * Reads public API behavior only; compact coefficients prevent enormous allocations.
 */
import java.io.File
import java.math.BigDecimal
import java.math.MathContext
import java.math.RoundingMode

check(Runtime.version().toString() in listOf("25.0.4+9", "25.0.4+9-LTS")) { "Requires JDK 25.0.4+9" }
check(args.all { it == "--check" }) { "Usage: generate-scale-oracle.main.kts [--check]" }
val scales = listOf(Int.MIN_VALUE, Int.MIN_VALUE + 1, Int.MIN_VALUE + 5, -1, 0, 1, Int.MAX_VALUE - 5, Int.MAX_VALUE - 1, Int.MAX_VALUE)
val inputs = listOf(-1000L, -100, -3, -1, 0, 1, 3, 100, 1000).flatMap { n -> scales.map { BigDecimal.valueOf(n, it) } }
val results = mutableListOf<String>()
fun record(action: () -> Any?) {
    results += try { action().toString() } catch (e: Exception) { "!${e.javaClass.simpleName}" }
}
for (x in inputs) {
    record { BigDecimal(x.toString()) }
    record { x.toEngineeringString() }
    record { x.stripTrailingZeros() }
    for (y in inputs) {
        record { x.multiply(y) }
        record { x.divide(y) }
        for (p in listOf(1, 2, 7)) for (mode in listOf(RoundingMode.DOWN, RoundingMode.HALF_EVEN, RoundingMode.UNNECESSARY)) {
            val context = MathContext(p, mode)
            record { x.divide(y, context) }
            record { x.add(y, context) }
        }
    }
    for (p in listOf(0, 1, 2, 7)) for (mode in RoundingMode.entries) {
        val context = MathContext(p, mode)
        record { x.sqrt(context) }
        record { x.round(context) }
        record { x.pow(2, context) }
    }
}
// One outcome per line, chunked below the JVM constant-pool UTF-8 limit. These
// are full expected values, not hashes; every case gets an exact comparison.
val chunks = results.chunked(500)
val source = buildString {
    appendLine("// SPDX-License-Identifier: Apache-2.0")
    appendLine("// Generated by scripts/generate-scale-oracle.main.kts; JDK 25.0.4+9.")
    appendLine("// ${results.size} full expected outcomes; do not edit.")
    appendLine("package io.heapy.krogu.math")
    appendLine()
    appendLine("internal fun scaleBoundaryExpected(): Sequence<String> = sequenceOf(")
    for (i in chunks.indices) appendLine("    scaleExpectedChunk$i(),")
    appendLine(").flatMap { it.lineSequence() }")
    for ((i, chunk) in chunks.withIndex()) {
        val literal = chunk.joinToString("\\n")
        check('"' !in literal && '$' !in literal && literal.toByteArray().size < 60000)
        appendLine("\nprivate fun scaleExpectedChunk$i(): String = \"$literal\"")
    }
}
val target = File("src/commonTest/kotlin/io/heapy/krogu/math/Jdk25ScaleBoundaryResults.kt")
if ("--check" in args) {
    check(target.exists() && target.readText() == source) { "Scale boundary oracle differs; regenerate with the pinned JDK" }
    println("Verified ${results.size} signed-scale-boundary outcomes")
} else {
    target.parentFile.mkdirs()
    target.writeText(source)
    println("Generated ${results.size} signed-scale-boundary outcomes in $target")
}
