/** BigInteger hash results from public JDK APIs. Usage: [--check]. */
import java.io.File
import java.math.BigInteger

check(Runtime.version().toString() in listOf("25.0.4+9", "25.0.4+9-LTS")) { "Requires JDK 25.0.4+9" }
check(args.all { it == "--check" }) { "Usage: generate-hash-oracle.main.kts [--check]" }
val powerLimit = 960
val sizes = listOf(1, 2, 3, 4, 5, 7, 8, 15, 16, 29, 30, 31, 32, 59, 60, 61, 63, 64, 65,
    119, 120, 121, 127, 128, 129, 255, 256, 257, 511, 512, 513, 1023, 1024, 4096, 65536)
val structured = mutableListOf<Int>()
for (power in 0 until powerLimit) for (offset in -1L..1L) {
    val magnitude = BigInteger.ONE.shiftLeft(power).add(BigInteger.valueOf(offset))
    for (sign in listOf(-1, 1)) structured += (if (sign < 0) magnitude.negate() else magnitude).hashCode()
}
val dense = mutableListOf<Int>()
for (size in sizes) for (pattern in 0..4) {
    val bytes = ByteArray(size) { index -> when (pattern) {
        0 -> 0
        1 -> 255
        2 -> 170
        3 -> 85
        else -> (index * 73 + size * 11) xor (index ushr 3)
    }.toByte() }
    for (sign in listOf(-1, 1)) dense += BigInteger(sign, bytes).hashCode()
}
val source = buildString {
    appendLine("// SPDX-License-Identifier: Apache-2.0")
    appendLine("// Generated by scripts/generate-hash-oracle.main.kts; JDK 25.0.4+9.")
    appendLine("package io.heapy.krogu.math")
    appendLine("internal const val JDK25_HASH_POWER_LIMIT = $powerLimit")
    appendLine("internal fun jdk25HashSizes(): IntArray = intArrayOf(${sizes.joinToString()})")
    fun results(name: String, values: List<Int>) {
        appendLine("internal fun $name(): Sequence<Int> = sequence {")
        for (chunk in values.chunked(250)) {
            appendLine("    yieldAll(\"\"\"")
            chunk.forEach { appendLine(it) }
            appendLine("\"\"\".trim().lineSequence().map { it.toInt() })")
        }
        appendLine("}")
    }
    results("jdk25StructuredHashResults", structured)
    results("jdk25DenseHashResults", dense)
}
val target = File("test/io/heapy/krogu/math/Jdk25HashResults.kt")
if ("--check" in args) check(target.readText() == source) { "Hash oracle is stale" }
else target.writeText(source)
println("Verified ${structured.size} structured and ${dense.size} dense hash outcomes.")
