/** Byte constructor values and diagnostics from public JDK APIs. Usage: [--check]. */
import java.io.File
import java.math.BigInteger

check(Runtime.version().toString() in listOf("25.0.4+9", "25.0.4+9-LTS")) { "Requires JDK 25.0.4+9" }
check(args.all { it == "--check" })
val arrays = linkedSetOf("", "00", "01", "7f", "80", "ff", "0000", "0001", "0080", "ff00", "ffff", "00ff00", "ff0000")
for (size in listOf(4, 7, 8, 9, 15, 16)) {
    arrays += "ff".repeat(size)
    arrays += "80" + "00".repeat(size - 1)
    arrays += "00" + "ff".repeat(size - 1)
}
val outcomes = linkedMapOf<String, Int>()
val rows = mutableListOf<String>()
fun record(mode: String, hex: String, sign: Int, off: Int, len: Int) {
    val bytes = hex.hexToByteArray()
    val result = try {
        when (mode) {
            "twos" -> BigInteger(bytes, off, len)
            "signed" -> BigInteger(sign, bytes, off, len)
            "whole" -> BigInteger(bytes)
            else -> BigInteger(sign, bytes)
        }.toString()
    } catch (e: Exception) { "!${e.javaClass.simpleName}:${e.message}" }
    val index = outcomes.getOrPut(result) { outcomes.size }
    rows += "$mode|$hex|$sign|$off|$len|$index"
}
for (hex in arrays) {
    val size = hex.length / 2
    val bounds = listOf(Int.MIN_VALUE, -2, -1, 0, 1, 2, size - 1, size, size + 1, Int.MAX_VALUE - 1, Int.MAX_VALUE).distinct()
    for (off in bounds) for (len in bounds) {
        record("twos", hex, 0, off, len)
        for (sign in listOf(Int.MIN_VALUE, -2, -1, 0, 1, 2, Int.MAX_VALUE)) record("signed", hex, sign, off, len)
    }
    record("whole", hex, 0, 0, size)
    for (sign in listOf(Int.MIN_VALUE, -2, -1, 0, 1, 2, Int.MAX_VALUE)) record("magnitude", hex, sign, 0, size)
}
val source = buildString {
    appendLine("// SPDX-License-Identifier: Apache-2.0")
    appendLine("// Generated by scripts/generate-integer-bytes-oracle.main.kts; JDK 25.0.4+9.")
    appendLine("package io.heapy.krogu.math")
    fun emit(name: String, values: List<String>) {
        check(values.none { '\n' in it || '\\' in it || '"' in it || '$' in it })
        val chunks = values.chunked(80)
        appendLine("internal fun $name(): List<String> = buildList {")
        for (index in chunks.indices) appendLine("    addAll(${name}Batch$index())")
        appendLine("}")
        for ((index, chunk) in chunks.withIndex()) {
            appendLine("private fun ${name}Batch$index(): List<String> = listOf(")
            for (value in chunk) appendLine("    \"$value\",")
            appendLine(")")
        }
    }
    emit("jdk25IntegerByteCases", rows)
    emit("jdk25IntegerByteOutcomes", outcomes.keys.toList())
}
val target = File("src/commonTest/kotlin/io/heapy/krogu/math/Jdk25IntegerByteResults.kt")
if ("--check" in args) check(target.exists() && target.readText() == source) { "Integer byte oracle differs" }
else target.writeText(source)
println("${if ("--check" in args) "Verified" else "Generated"} ${rows.size} byte constructor cases (${outcomes.size} outcomes)")
