class Probe(text: String, val label: String, val trace: StringBuilder, val mode: String) : BigInteger(text) {
    var other: BigInteger = BigInteger.ZERO
    val replacement = BigInteger(if (mode == "negative-fixed") "-7" else "7")
    private fun call(name: String) {
        trace.append("$label.$name;")
        if (mode == "$name:throw") throw IllegalStateException("$name callback")
    }
    override fun toByte(): Byte = super.toInt().toByte()
    override fun toShort(): Short = super.toInt().toShort()
    override fun abs(): BigInteger {
        call("abs")
        return when (mode) {
            "abs:self" -> this
            "abs:other" -> other
            "abs:fixed", "negative-fixed" -> replacement
            else -> super.abs()
        }
    }
    override fun negate(): BigInteger {
        call("negate")
        return when (mode) {
            "negate:self" -> this
            "negate:other" -> other
            "negate:fixed" -> replacement
            else -> super.negate()
        }
    }
    override fun remainder(other: BigInteger): BigInteger { call("rem"); return super.remainder(other) }
    override fun divideAndRemainder(other: BigInteger): Array<BigInteger> { call("pair"); return super.divideAndRemainder(other) }
    private fun poison(name: String): Nothing { trace.append("$label.$name;"); throw IllegalStateException("$name callback") }
    override fun equals(other: Any?): Boolean = poison("equals")
    override fun signum(): Int = poison("signum")
    override fun compareTo(other: BigInteger): Int = poison("compare")
    override fun bitLength(): Int = poison("bits")
    override fun getLowestSetBit(): Int = poison("lowest")
    override fun shiftRight(n: Int): BigInteger = poison("right")
    override fun subtract(other: BigInteger): BigInteger = poison("subtract")
}
fun outcome(a: String, b: String, mode: String, alias: Boolean): String {
    val trace = StringBuilder()
    val left = Probe(a, "L", trace, mode)
    val right = if (alias) left else Probe(b, "R", trace, mode)
    left.other = right; right.other = left
    return try {
        val value = left.gcd(right)
        val calls = trace.toString()
        val text = if (value === left) a else if (value === right) b else value.toString()
        "$text|${value === left}|${value === right}|${value === left.replacement}|${value === right.replacement}|${value === BigInteger.ZERO}|${value === BigInteger.ONE}|${value::class == BigInteger::class}|$calls"
    } catch (e: Exception) { "!${e.javaClass.simpleName}:${e.message}|$trace" }
}
