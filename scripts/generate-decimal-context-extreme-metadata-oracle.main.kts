/** Diagnostic public-JDK observations with contract-violating metadata. Usage: [--check] [--trace]. */
import java.math.BigDecimal
import java.math.BigInteger
import java.math.MathContext
import java.math.RoundingMode
import java.io.File
check(Runtime.version().toString() in listOf("25.0.4+9", "25.0.4+9-LTS"))
check(args.all { it in listOf("--check", "--trace") })
class ExtremeProbe(coefficient: String, scale: Int, val digits: Int, val forceSign: Boolean,
    val label: String, val trace: StringBuilder) : BigDecimal(BigInteger(coefficient), scale) {
    override fun toByte(): Byte = super.toInt().toByte()
    override fun toShort(): Short = super.toInt().toShort()
    override fun signum(): Int {
        trace.append("$label.sign;")
        return if (forceSign) 1 else super.signum()
    }
    override fun precision(): Int { trace.append("$label.precision;"); return digits }
    fun enter(v: BigDecimal, p: Int, rounding: String): BigDecimal =
        super.divide(v, MathContext(p, RoundingMode.valueOf(rounding)))
}
fun extremeOutcome(a: String, b: String, aScale: Int, bScale: Int, x: Int, y: Int,
    forced: Boolean, p: Int, rounding: String): String {
    val trace = StringBuilder()
    val source = ExtremeProbe(a, aScale, x, forced, "A", trace)
    val divisor = ExtremeProbe(b, bScale, y, forced, "B", trace)
    return try {
        val result = source.enter(divisor, p, rounding)
        val calls = trace.toString()
        "${result.toString()}:${result.scale()}|$calls"
    } catch (e: Exception) { "!${e::class.simpleName}:${e.message}|$trace" }
}
val metadata = listOf(
    Int.MIN_VALUE to Int.MIN_VALUE, Int.MIN_VALUE to Int.MIN_VALUE + 1,
    Int.MIN_VALUE + 1 to Int.MIN_VALUE, Int.MIN_VALUE to Int.MIN_VALUE + 18,
    Int.MIN_VALUE + 18 to Int.MIN_VALUE, Int.MIN_VALUE to Int.MIN_VALUE + 19,
    Int.MAX_VALUE to Int.MAX_VALUE, Int.MAX_VALUE - 1 to Int.MAX_VALUE,
    Int.MAX_VALUE to Int.MAX_VALUE - 1, Int.MAX_VALUE - 18 to Int.MAX_VALUE,
    Int.MAX_VALUE to 0, 0 to Int.MAX_VALUE, Int.MIN_VALUE to 0, 0 to Int.MIN_VALUE,
    Int.MIN_VALUE to Int.MAX_VALUE, Int.MAX_VALUE to Int.MIN_VALUE
)
val inputs = listOf("1" to "1", "1" to "3", "1000" to "20", "-1000" to "20",
    "1" to "123456789012345678901234567890123", "123456789012345678901234567890123" to "3",
    "0" to "1", "0" to "0")
val rows = mutableListOf<List<String>>()
fun add(a: String, b: String, aScale: Int, bScale: Int, x: Int, y: Int, forced: Boolean, p: Int, rounding: String) {
    val input = listOf(a, b, aScale.toString(), bScale.toString(), x.toString(), y.toString(), forced.toString(), p.toString(), rounding)
    if ("--trace" in args) println("Case ${rows.size}: $input")
    rows += input + extremeOutcome(a, b, aScale, bScale, x, y, forced, p, rounding)
}
for ((a, b) in inputs) for ((x, y) in metadata) for (forced in listOf(false, true))
    for (p in listOf(1, 17, 18, 19)) for (rounding in RoundingMode.entries)
        add(a, b, 0, 0, x, y, forced, p, rounding.name)
val generated = buildString {
    appendLine("// SPDX-License-Identifier: Apache-2.0")
    appendLine("// Generated by scripts/generate-decimal-context-extreme-metadata-oracle.main.kts; JDK 25.0.4+9.")
    appendLine("package io.heapy.krogu.math")
    appendLine("internal fun jdk25DecimalContextExtremeMetadataCases(): List<Array<String>> = listOf(")
    for (chunk in rows.chunked(100)) {
        appendLine("    \"\"\"")
        for (row in chunk) appendLine(row.joinToString("\t"))
        appendLine("    \"\"\".trimIndent(),")
    }
    appendLine(").flatMap { it.lines().map { line -> line.split('\\t').toTypedArray() } }")
}
val target = File("diagnostics/decimal-context-extreme-metadata/Jdk25DecimalContextExtremeMetadataResults.kt")
if ("--check" in args) check(target.exists() && target.readText() == generated) { "Extreme context metadata oracle differs" }
else target.writeText(generated)
println("${if ("--check" in args) "Verified" else "Generated"} ${rows.size} extreme context metadata cases")
