    lines.forEachIndexed { lineIndex, line ->
        if (line.trimStart().startsWith("arrayOf(")) {
            val v = literals.findAll(line).map { it.groupValues[1] }.toList()
            val classification = if (v.size != 7 || v[0] !in listOf("A", "N", "H")) null else {
                val exactContext = v[4] == "0" || v[5] == "UNNECESSARY"
                when (v[0]) {
                    "A" -> if (exactContext && v[3].toInt() % 2 == 0) "A.normalized-getter" else null
                    "N" -> if (exactContext) "N.normalized-replacement-getter" else null
                    else -> if (v[2] !in listOf("1", "4.00", "0.0004")) null else when (v[1]) {
                        "sqrt" -> if (!exactContext) "H.sqrt.precision" else null
                        "sqrtSign" -> if (!exactContext && v[3] == "1") "H.sqrtSign.precision" else null
                        "sqrtPrecision" -> if (!exactContext) "H.sqrtPrecision.metadata" else null
                        "sqrtNormalize" -> if (exactContext) "H.sqrtNormalize.strip" else "H.sqrtNormalize.precision"
                        else -> null
                    }
                }
            }
            if (classification != null) {
                counts[classification] = (counts[classification] ?: 0) + 1
                selected.append("$index\t${lineIndex + 1}\t$classification\t${v.joinToString("\t")}\n")
                snapshotRows.add(listOf(index.toString(), classification) + v)
            }
            index++
        }
    }
}
