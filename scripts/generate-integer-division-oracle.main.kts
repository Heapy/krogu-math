check(args.all { it == "--check" })
class Probe(text: String, val label: String, val trace: StringBuilder, val mode: String) : BigInteger(text) {
    private val replacement = BigInteger("7")
    private fun call(name: String) {
        trace.append("$label.$name;")
        if (mode == "throw") throw IllegalStateException("$name callback")
    }
    override fun toByte(): Byte = super.toInt().toByte()
    override fun toShort(): Short = super.toInt().toShort()
    override fun abs(): BigInteger { call("abs"); return if (mode == "replace") replacement else super.abs() }
    override fun negate(): BigInteger { call("negate"); return if (mode == "replace") replacement else super.negate() }
    override fun signum(): Int { call("signum"); return if (mode == "replace") -7 else super.signum() }
    override fun bitLength(): Int { call("bitLength"); return if (mode == "replace") 1 else super.bitLength() }
    override fun compareTo(other: BigInteger): Int { call("compare"); return if (mode == "replace") 0 else super.compareTo(other) }
    override fun testBit(n: Int): Boolean { call("testBit"); return if (mode == "replace") false else super.testBit(n) }
    override fun add(other: BigInteger): BigInteger { call("add"); return if (mode == "replace") replacement else super.add(other) }
    override fun subtract(other: BigInteger): BigInteger { call("subtract"); return if (mode == "replace") replacement else super.subtract(other) }
    override fun shiftLeft(n: Int): BigInteger { call("shiftLeft"); return if (mode == "replace") replacement else super.shiftLeft(n) }
    override fun divideAndRemainder(other: BigInteger): Array<BigInteger> {
        call("pair")
        return when (mode) {
            "replace" -> arrayOf(replacement, replacement)
            "empty-pair" -> emptyArray()
            else -> super.divideAndRemainder(other)
        }
    }
    fun inheritedPair(other: BigInteger): Array<BigInteger> = super.divideAndRemainder(other)
}
fun outcome(leftText: String, rightText: String, op: String, mode: String, alias: Boolean): String {
    val trace = StringBuilder()
    val left = Probe(leftText, "L", trace, mode)
    val right = if (alias) left else Probe(rightText, "R", trace, mode)
    return try {
        val values = when (op) {
            "divide" -> arrayOf(left.divide(right))
            "remainder" -> arrayOf(left.remainder(right))
            else -> left.inheritedPair(right)
        }
        val calls = trace.toString()
        values.joinToString("|") {
            val text = if (it === left) leftText else if (it === right) rightText else it.toString()
            "$text:${it === left}:${it === right}:${it === BigInteger.ZERO}:${it === BigInteger.ONE}:${it === BigInteger.TWO}:${it === BigInteger.TEN}:${it::class == BigInteger::class}"
        } + "|same=${values.size == 2 && values[0] === values[1]}|$calls"
    } catch (e: Exception) { "!${e.javaClass.simpleName}:${e.message}|$trace" }
}
val rows = mutableListOf<List<String>>()
fun record(a: String, b: String, alias: Boolean = false) {
    for (op in listOf("divide", "remainder", "pair"))
        for (mode in listOf("delegate", "throw", "replace", "empty-pair"))
            rows += listOf(a, b, op, mode, alias.toString(), outcome(a, b, op, mode, alias))
}
val inputs = listOf("0", "1", "-1", "100", "-100", "123456789012345678901234567890", "-123456789012345678901234567890")
val divisors = listOf("0", "1", "-1", "3", "-3", "1073741823", "1073741824", "12345678901234567890", "-12345678901234567890")
for (a in inputs) for (b in divisors) record(a, b)
for (a in inputs) record(a, a, true)
// Small final remainders exercise the last binary-division step and object identities.
for (bits in listOf(29, 30, 90)) {
    val d = BigInteger.ONE.shiftLeft(bits)
    for (q in 1L..4L) for (r in listOf(0L, 1L, 2L, 10L)) {
        val a = d.multiply(BigInteger.valueOf(q)).add(BigInteger.valueOf(r))
        for (leftSign in listOf(1L, -1L)) for (rightSign in listOf(1L, -1L))
            record(a.multiply(BigInteger.valueOf(leftSign)).toString(), d.multiply(BigInteger.valueOf(rightSign)).toString())
    }
}
for (bits in listOf(1024, 4096)) {
    val a = BigInteger.ONE.shiftLeft(bits * 2).subtract(BigInteger.ONE)
    val b = BigInteger.ONE.shiftLeft(bits).add(BigInteger.valueOf(17))
    for (sign in listOf(1, -1)) record(a.multiply(BigInteger.valueOf(sign.toLong())).toString(), b.toString())
    record(b.toString(), a.toString())
}
val source = buildString {
    appendLine("// SPDX-License-Identifier: Apache-2.0")
    appendLine("// Generated by scripts/generate-integer-division-oracle.main.kts; JDK 25.0.4+9.")
    appendLine("package io.heapy.krogu.math")
    val chunks = rows.chunked(30)
    appendLine("internal fun jdk25IntegerDivisionCases(): List<Array<String>> = buildList {")
    for (index in chunks.indices) appendLine("    addAll(integerDivisionBatch$index())")
    appendLine("}")
    for ((index, chunk) in chunks.withIndex()) {
        appendLine("private fun integerDivisionBatch$index(): List<Array<String>> = listOf(")
        for (row in chunk) appendLine("    arrayOf(${row.joinToString(", ") { "\"$it\"" }}),")
        appendLine(")")
    }
}
